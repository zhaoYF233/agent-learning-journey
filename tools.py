def get_weather(city):
    """
    模拟查询天气的工具函数。
    真实项目中，这里会调用高德、OpenWeatherMap 等真实天气 API。
    今天先用模拟数据，目的是跑通 Agent 的工具调用流程。
    """
    # 预设几个城市的天气数据
    weather_database = {
        "北京": "北京今天晴朗，气温 25℃，空气质量优。",
        "上海": "上海今天多云转阴，气温 22℃，有轻微雾霾。",
        "广州": "广州今天雷阵雨，气温 30℃，湿度较大。",
        "深圳": "深圳今天晴间多云，气温 28℃，适合户外活动。"
    }

    # 如果查询的城市在预设字典里，返回对应天气；否则返回默认描述
    return weather_database.get(city, f"{city}今天多云，气温 18℃左右。")# 去 weather_database 这个字典里，查找键为 city 对应的值
#如果字典里存在这个键，就直接返回该键对应的值（比如城市的天气数据），如果字典里不存在这个键，就返回第二个参数 f"{city}"（这里是把 city 变量本身作为默认值返回）
if __name__=="__main__":
    print(get_weather("北京"))                    #  找到了
    print(get_weather("洛阳"))                    #  没找到